import { expect, test } from '@playwright/test'
import { account } from './fixtures/session'

test('category selection works inside a modal ledger form', async ({ page, request }) => {
  await account(page, request)
  await page.goto('/personal')
  await page.getByRole('button', { name: 'Not now' }).click({ timeout: 1500 }).catch(() => {})
  await page.getByRole('button', { name: 'Add record', exact: true }).click()
  const drawer = page.getByRole('dialog', { name: 'Add record', exact: true })
  await expect(drawer).toBeVisible()
  await drawer.locator('.category-trigger').click()
  const category = page.getByRole('listbox', { name: 'Category', exact: true })
  await expect(category).toBeVisible()
  await category.getByRole('button', { name: 'Uncategorized', exact: true }).click({ timeout: 3000 })
  await expect(category).toBeHidden()
  await drawer.locator('.category-trigger').click()
  await page.keyboard.press('Escape')
  await expect(category).toBeHidden()
  await expect(drawer).toBeVisible()
  await expect(drawer.locator('.category-trigger')).toBeFocused()
  await drawer.locator('.category-trigger').click()
  // Inject a reduced visual viewport to model an on-screen keyboard.
  await page.evaluate(() => {
    if (!window.visualViewport) throw new Error('visual viewport unavailable')
    Object.defineProperty(window.visualViewport, 'height', { configurable: true, get: () => 350 })
    window.visualViewport.dispatchEvent(new Event('resize'))
  })
  await expect.poll(async () => (await category.boundingBox())!.y + (await category.boundingBox())!.height).toBeLessThanOrEqual(351)
  await category.getByRole('button', { name: 'Uncategorized', exact: true }).click()
  await page.evaluate(() => Reflect.deleteProperty(window.visualViewport!, 'height'))
  await drawer.locator('.category-trigger').click()
  await page.locator('.category-menu').getByRole('button', { name: 'Add category', exact: true }).click()
  await page.locator('.category-create .icon-trigger').click()
  const icons = page.locator('.icon-menu')
  await expect(icons).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(icons).toBeHidden()
  await expect(page.locator('.category-menu')).toBeVisible()
  await expect(drawer).toBeVisible()
})
